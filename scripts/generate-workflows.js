const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const registryPath = path.join(root, 'config', 'workflows.json');
const header = '# Generated by scripts/generate-workflows.js. Edit config/workflows.json or .github/templates instead.\n';

function renderWorkflows(registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'))) {
  if (!Array.isArray(registry.nodeVersions) || !registry.nodeVersions.length ||
      registry.nodeVersions.some(version => typeof version !== 'string' || !/^\d+$/.test(version)) ||
      new Set(registry.nodeVersions).size !== registry.nodeVersions.length)
    throw new Error('Node versions must be a unique, non-empty list of major versions.');
  if (!Number.isInteger(registry.shards) || registry.shards < 1 || registry.shards > 8)
    throw new Error('Shard count must be an integer between 1 and 8.');
  if (!/^[a-z0-9-]+$/.test(registry.browserEnvironment))
    throw new Error('Use a simple environment name.');
  if (typeof registry.smokeGrep !== 'string' || !registry.smokeGrep.trim())
    throw new Error('A smoke test filter is required.');
  const tokens = {
    NODE_VERSIONS: JSON.stringify(registry.nodeVersions),
    SHARD_COUNT: String(registry.shards),
    SHARDS: JSON.stringify(Array.from({ length: registry.shards }, (_, index) => index + 1)),
    BROWSER_ENVIRONMENT: registry.browserEnvironment,
    SMOKE_GREP: JSON.stringify(registry.smokeGrep),
  };
  for (const [name, action] of Object.entries(registry.actions)) {
    if (!/^[a-z_]+$/.test(name) || !/^[\w.-]+\/[\w.-]+@[a-f0-9]{40}$/.test(action.ref) ||
        !/^v\d+\.\d+\.\d+$/.test(action.version))
      throw new Error('External actions require a full commit SHA and a version comment.');
    tokens['ACTION_' + name.toUpperCase()] = `${action.ref} # ${action.version}`;
  }
  if (!Array.isArray(registry.workflows) || !registry.workflows.length)
    throw new Error('Declare at least one workflow.');
  const rendered = new Map();
  for (const workflow of registry.workflows) {
    if (![workflow.file, workflow.template].every(name => /^[a-z0-9-]+\.yml$/.test(name)))
      throw new Error('Workflow filenames must stay inside the managed directories.');
    if (rendered.has(workflow.file)) throw new Error('Duplicate workflow filename.');
    const template = path.join(root, '.github/templates', workflow.template);
    if (!fs.lstatSync(template).isFile()) throw new Error('Workflow templates must be regular files.');
    let content = fs.readFileSync(template, 'utf8');
    content = content.replace(/@@([A-Z_]+)@@/g, (_, token) => {
      if (!(token in tokens)) throw new Error(`Unknown template token: ${token}`);
      return tokens[token];
    });
    if (/@@[^@\r\n]+@@/.test(content)) throw new Error('Unresolved template token.');
    rendered.set(workflow.file, header + content.trimEnd() + '\n');
  }
  return rendered;
}

function syncWorkflows(outputDir, check = false, rendered = renderWorkflows()) {
  const drift = [];
  for (const [name, expected] of rendered) {
    const file = path.join(outputDir, name);
    const existing = fs.lstatSync(file, { throwIfNoEntry: false });
    if (existing && !existing.isFile())
      throw new Error('Generated outputs must be regular files.');
    if (!existing || fs.readFileSync(file, 'utf8') !== expected) {
      drift.push(name);
      if (!check) {
        fs.mkdirSync(outputDir, { recursive: true });
        fs.writeFileSync(file, expected);
      }
    }
  }
  if (fs.existsSync(outputDir)) {
    for (const name of fs.readdirSync(outputDir)) {
      if (!name.endsWith('.yml') || rendered.has(name)) continue;
      const file = path.join(outputDir, name);
      if (fs.statSync(file).isFile() && fs.readFileSync(file, 'utf8').startsWith(header)) {
        drift.push(name);
        if (!check) fs.unlinkSync(file);
      }
    }
  }
  return drift;
}

if (require.main === module) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) {
    console.error('Usage: node scripts/generate-workflows.js [--check]');
    process.exitCode = 1;
  } else {
    const check = process.argv.includes('--check');
    const drift = syncWorkflows(path.join(root, '.github/workflows'), check);
    if (check && drift.length) {
      console.error('Generated workflow drift: ' + drift.join(', ') + '. Run npm run generate:workflows.');
      process.exitCode = 1;
    } else console.log(check ? 'Generated workflows are current.' : 'Generated workflows updated.');
  }
}
module.exports = { renderWorkflows, syncWorkflows };
